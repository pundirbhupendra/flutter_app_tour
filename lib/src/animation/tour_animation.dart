/// Defines the available highlight animations for tour steps.
enum TourAnimation {
  /// No animation.
  none,

  /// A subtle pulsing scale animation around the highlight.
  pulse,

  /// A soft glow effect via shadow and opacity.
  glow,

  /// A ripple expanding out from the target.
  ripple,

  /// A quick bounce movement.
  bounce,

  /// A slow floating/hovering translation.
  floating,
}
